import {execFileSync} from 'node:child_process';
import {mkdirSync,cpSync,writeFileSync,readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
execFileSync('dotnet',['publish','src/Runtime/Runtime.csproj','-c','Release','-o','.build/runtime'],{stdio:'inherit'});
mkdirSync('dist',{recursive:true});
cpSync('.build/runtime/wwwroot','dist',{recursive:true});
cpSync('web','dist',{recursive:true});
const arcadeCSS=readFileSync('web/arcade.css');
const arcadeName='arcade.'+createHash('sha256').update(arcadeCSS).digest('hex').slice(0,12)+'.css';
writeFileSync('dist/'+arcadeName,arcadeCSS);
const versioned=(name,body=readFileSync('web/'+name))=>{const dot=name.lastIndexOf('.');const target=name.slice(0,dot)+'.'+createHash('sha256').update(body).digest('hex').slice(0,12)+name.slice(dot);writeFileSync('dist/'+target,body);return target;};
const baseStyle=versioned('style.css');
const catalog=versioned('catalog.js');
const worker=versioned('python-worker.js');
const sourceMapName='sources.'+createHash('sha256').update(JSON.stringify(['originales/Calculo de compra.py','originales/Program (1).cs','nuevos/Calificaciones.py','originales/Inventario.py','originales/Program.cs','nuevos/Reporte_ventas.py'].map(p=>readFileSync(p,'utf8')))).digest('hex').slice(0,12)+'.json';
const app=versioned('app.js',readFileSync('web/app.js','utf8').replace("'./catalog.js'","'./"+catalog+"'").replace("new Worker('python-worker.js')","new Worker('"+worker+"')").replace("fetch('sources.json')","fetch('"+sourceMapName+"')"));
const buildId=createHash('sha256').update(arcadeName+baseStyle+catalog+worker+app).digest('hex').slice(0,12);
writeFileSync('dist/version.json',JSON.stringify({version:buildId}));
writeFileSync('dist/index.html',readFileSync('web/index.html','utf8').replace('href="arcade.css"','href="'+arcadeName+'"').replace('href="style.css"','href="'+baseStyle+'"').replace('src="app.js"','src="'+app+'"').replace('</head>','<meta name="codelab-build" content="'+buildId+'"></head>'));
cpSync('originales','dist/originales',{recursive:true});
cpSync('nuevos','dist/nuevos',{recursive:true});
cpSync('ejemplos','dist/ejemplos',{recursive:true});
cpSync('README.md','dist/README.md');
cpSync('VALIDACION.md','dist/VALIDACION.md');
cpSync('pruebas-obtenidas.json','dist/pruebas-obtenidas.json');
writeFileSync('dist/.nojekyll','');
const paths={1:'originales/Calculo de compra.py',2:'originales/Program (1).cs',3:'nuevos/Calificaciones.py',4:'originales/Inventario.py',5:'originales/Program.cs',6:'nuevos/Reporte_ventas.py'};
writeFileSync('dist/sources.json',JSON.stringify(Object.fromEntries(Object.entries(paths).map(([id,path])=>[id,{path,file:path.split('/').at(-1),code:readFileSync(path,'utf8'),kind:path.startsWith('nuevos/')?'nuevo':'original'}]))));
cpSync('dist/sources.json','dist/'+sourceMapName);
